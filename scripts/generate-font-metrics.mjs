/**
 * Extracts advance widths and vertical metrics from the vendored fonts into a static table.
 *
 * Why a precomputed table rather than parsing fonts at runtime: `measureRunWidth` is called
 * synchronously all over the render path, so a runtime font load would either force that whole
 * path async or leave a window where measurement silently falls back to a different
 * implementation. That fallback is exactly the bug this phase exists to remove. A table is
 * synchronous, identical in the browser and in `node --test`, and small.
 *
 * Run with `pnpm fonts:metrics` after changing the vendored faces.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = path.join(rootDir, 'public', 'fonts');
const OUT_FILE = path.join(rootDir, 'src', 'lib', 'generated', 'fontMetrics.ts');

/** Metric-compatible substitutes: Sans≡Arial, Serif≡Times New Roman, Mono≡Courier New. */
const FAMILIES = {
  sans: 'LiberationSans',
  serif: 'LiberationSerif',
  mono: 'LiberationMono',
};

const FACES = {
  regular: 'Regular',
  bold: 'Bold',
  italic: 'Italic',
  boldItalic: 'BoldItalic',
};

/**
 * Codepoint ranges worth tabulating. Anything outside these falls back to the face's default
 * advance at runtime, which is why `notdef` width is recorded too.
 */
const RANGES = [
  [0x20, 0x24f], // Latin + Latin-1 Supplement + Latin Extended-A/B
  [0x2c6, 0x2dd], // spacing modifiers used by some encodings
  [0x370, 0x3ff], // Greek (alpha, beta, mu, ... common in chemistry)
  [0x2000, 0x206f], // General punctuation (dashes, primes, thin spaces)
  [0x2070, 0x209f], // Superscripts and subscripts
  [0x20a0, 0x20bf], // Currency
  [0x2100, 0x214f], // Letterlike symbols
  [0x2190, 0x21ff], // Arrows
  [0x2200, 0x22ff], // Mathematical operators
  [0x25a0, 0x25ff], // Geometric shapes (bullets used in captions)
];

function extractFace(filePath) {
  const buffer = readFileSync(filePath);
  const font = opentype.parse(
    buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength),
  );
  const unitsPerEm = font.unitsPerEm;
  const os2 = font.tables.os2 ?? {};

  const advances = {};
  for (const [start, end] of RANGES) {
    for (let cp = start; cp <= end; cp += 1) {
      const glyph = font.charToGlyph(String.fromCodePoint(cp));
      // charToGlyph falls back to .notdef (index 0) for uncovered codepoints; skip those so the
      // runtime fallback applies instead of baking in a wrong width.
      if (!glyph || glyph.index === 0) continue;
      if (typeof glyph.advanceWidth !== 'number') continue;
      advances[cp] = glyph.advanceWidth;
    }
  }

  return {
    unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    // sCapHeight/sxHeight are optional in OS/2 v2+; fall back to well-known ratios if absent.
    capHeight: os2.sCapHeight ?? Math.round(unitsPerEm * 0.716),
    xHeight: os2.sxHeight ?? Math.round(unitsPerEm * 0.523),
    defaultAdvance: font.glyphs.get(0)?.advanceWidth ?? Math.round(unitsPerEm * 0.5),
    advances,
  };
}

const table = {};
for (const [familyKey, fileFamily] of Object.entries(FAMILIES)) {
  table[familyKey] = {};
  for (const [faceKey, fileFace] of Object.entries(FACES)) {
    const filePath = path.join(FONT_DIR, `${fileFamily}-${fileFace}.ttf`);
    table[familyKey][faceKey] = extractFace(filePath);
    process.stdout.write(
      `${fileFamily}-${fileFace}: ${Object.keys(table[familyKey][faceKey].advances).length} glyphs\n`,
    );
  }
}

const banner = `// GENERATED by scripts/generate-font-metrics.mjs -- do not edit.
// Source: the vendored Liberation faces in public/fonts/ (SIL OFL).
// Regenerate with \`pnpm fonts:metrics\`.
`;

const body = `${banner}
export interface FaceMetrics {
  unitsPerEm: number;
  ascender: number;
  descender: number;
  capHeight: number;
  xHeight: number;
  defaultAdvance: number;
  /** Codepoint -> advance width, in font units. */
  advances: Record<number, number>;
}

export type MetricFamily = 'sans' | 'serif' | 'mono';
export type MetricFace = 'regular' | 'bold' | 'italic' | 'boldItalic';

export const FONT_METRICS: Record<MetricFamily, Record<MetricFace, FaceMetrics>> =
  ${JSON.stringify(table)} as const;
`;

writeFileSync(OUT_FILE, body);
process.stdout.write(`\nwrote ${path.relative(rootDir, OUT_FILE)}\n`);
