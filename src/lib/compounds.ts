/**
 * Whole-molecule acronyms: solvents, bases, reagents, ligands, catalysts and the like.
 *
 * These are the labels that are not substituents. A `Boc` is drawn on an atom and bonds to the
 * rest of a molecule; `DMF` stands for the molecule. They resolve only for an atom with no bonds,
 * where they expand to the whole structure, and are listed in the alias library next to the
 * substituent shorthands. A label that is both (THF as tetrahydrofuranyl, TFA as trifluoroacetyl)
 * keeps its substituent meaning on a bonded atom.
 *
 * Definitions are the literature meaning of each acronym, validated with RDKit when added, and
 * cross-checked against the expansions ChemDraw saves for isolated labels where it has any
 * (`tests/compounds.test.mjs`). Salts and complexes are written as dot-separated components.
 */
export interface CompoundEntry {
  /** Every spelling that resolves to this compound; the first is the preferred label. */
  labels: string[];
  name: string;
  smiles: string;
  group:
    | 'solvent'
    | 'base'
    | 'acid'
    | 'lewis acid'
    | 'reductant'
    | 'oxidant'
    | 'organometallic'
    | 'catalyst'
    | 'ligand'
    | 'coupling'
    | 'protecting'
    | 'acylating'
    | 'sulfonylating'
    | 'alkylating'
    | 'halogenating'
    | 'initiator'
    | 'additive'
    | 'drying agent'
    | 'nmr'
    | 'reagent';
}

