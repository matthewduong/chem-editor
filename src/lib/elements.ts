/**
 * VALENCIES — single fixed valency per element, derived from ELEMENTS.
 * Only elements with exactly one known valency state are included.
 * Elements absent from this map have variable valency (metals, noble-gas-like, etc.)
 * and should NOT trigger valence-error highlights.
 */
export const VALENCIES: Record<string, number> = Object.fromEntries(
  Object.entries(ELEMENTS)
    .filter(([, d]) => d.valencies.length === 1)
    .map(([sym, d]) => [sym, d.valencies[0]]),
);

/**
 * ELEMENT_COLORS — CPK hex color per element, derived from ELEMENTS.
 */
export const ELEMENT_COLORS: Record<string, string> = Object.fromEntries(
  Object.entries(ELEMENTS).map(([sym, d]) => [sym, d.color]),
);

export function isElementSymbol(value: string): boolean {
  return Object.prototype.hasOwnProperty.call(ELEMENTS, value);
}
