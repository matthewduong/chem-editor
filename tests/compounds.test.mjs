test('compound definitions have the heavy-atom composition ChemDraw expands them to', () => {
  const composition = (smiles) => {
    const counts = {};
    for (const token of smiles.match(
      /\[[^\]]+\]|Cl|Br|Si|Sn|Se|Li|Na|Mg|Zn|Al|Pd|Cu|Ti|Fe|Mn|Os|Cs|Sc|Yb|Ce|Rh|Ru|Pt|Ni|Cr|[BCNOPSFIKbcnops]/g,
    ) ?? []) {
      const symbol = token.startsWith('[')
        ? (/^\[(?:\d+)?([A-Z][a-z]?)/.exec(token)?.[1] ?? '')
        : token.toUpperCase().replace(/^CL$/, 'Cl').replace(/^BR$/, 'Br');
      if (!symbol || symbol === 'H') continue;
      const key = symbol.length === 2 ? symbol[0] + symbol[1].toLowerCase() : symbol;
      counts[key] = (counts[key] ?? 0) + 1;
    }
    return JSON.stringify(Object.fromEntries(Object.entries(counts).sort()));
  };
  for (const [label, chemdraw] of CHEMDRAW_COMPOSITION_AGREES) {
    const entry = findCompound(label);
    assert.ok(entry, label);
    assert.equal(composition(entry.smiles), composition(chemdraw), label);
  }
});
