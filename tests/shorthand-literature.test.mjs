test('audited substituent acronyms resolve to their literature structure', () => {
  for (const [label, lead, valency, smiles] of DEFINED) {
    const resolution = resolveAliasChemistry(label);
    assert.equal(resolution.ok, true, `${label} resolves`);
    const entry = resolution.selected.entry;
    assert.equal(entry.lead, lead, `${label} lead`);
    assert.equal(entry.valency, valency, `${label} valency`);
    assert.equal(
      smilesStructureKey(resolution.selected.subsSmiles ?? entry.subsSmiles),
      smilesStructureKey(smiles),
      `${label} structure`,
    );
  }
});

